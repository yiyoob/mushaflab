"""M0.5: the mark order of the KFGQPC Madinah convention, derived from the Hafs word table.

For every pair of marks seen on one letter, count which comes first. A pair seen in both orders
takes the majority order; the letters written the other way are listed as exceptions. The order
is then a topological sort of the pairs (ties broken by codepoint, so the result is
deterministic). Nothing here says what a mark means (D72 level b, G-226): only the order in which
the KFGQPC Hafs text writes them, so a reading that adds a mark can place it where KFGQPC would.

    python -m pipeline.corpus_dabt write | check
"""

import sys
from collections import Counter
from pathlib import Path

from pipeline import corpus_words
from pipeline.clusterize import clusterize
from pipeline.codepoints import load_table

OUT = corpus_words.REPO / "corpus" / "dabt" / "kfgqpc-madinah.yaml"


def _letters() -> list[tuple[str, list[int]]]:
    """(letter id, marks) for every letter cluster of the word table, in text order."""
    table = load_table()
    out = []
    for line in corpus_words.OUT.read_text(encoding="utf-8").split("\n"):
        if not line or line.startswith(("#", "word_id\t")):
            continue
        word_id, _kind, text = line.split("\t")[:3]
        for n, c in enumerate(clusterize(text, table), 1):
            if c.kind == "letter":
                out.append((f"{word_id}:{n}", [ord(x) for x in c.text[1:]]))
    return out


def derive() -> tuple[list[int], list[tuple[str, list[int]]], int]:
    letters = _letters()
    pairs: Counter[tuple[int, int]] = Counter()
    for _, marks in letters:
        for i, a in enumerate(marks):
            for b in marks[i + 1 :]:
                pairs[(a, b)] += 1
    before: set[tuple[int, int]] = set()
    for (a, b), n in pairs.items():
        m = pairs.get((b, a), 0)
        if n > m or (n == m and a < b):
            before.add((a, b))
    marks = sorted({x for p in pairs for x in p} | {x for _, ms in letters for x in ms})
    order: list[int] = []
    left = set(marks)
    while left:
        free = [x for x in sorted(left) if not any((y, x) in before for y in left if y != x)]
        if not free:
            msg = f"mark order has a cycle among {sorted(left)}"
            raise ValueError(msg)
        order.append(free[0])
        left.remove(free[0])
    rank = {x: i for i, x in enumerate(order)}
    exceptions = [(lid, ms) for lid, ms in letters if ms != sorted(ms, key=rank.__getitem__)]
    return order, exceptions, len(letters)


def _cps(xs: list[int]) -> str:
    return ", ".join(f'"U+{x:04X}"' for x in xs)


def render() -> str:
    order, exceptions, n = derive()
    lines = [
        "# The KFGQPC Madinah writing convention (D72), as far as the Hafs text shows it.",
        "# Generated by `python -m pipeline.corpus_dabt write` from corpus/text/words.tsv.",
        "# Do not edit.",
        "id: kfgqpc-madinah",
        'title: "KFGQPC Madinah conventions, from the KFGQPC Hafs text v2.0"',
        f"letters: {n}",
        "mark_order:",
        "  source: kfgqpc-hafs:all",
        "  status: raw-derived",
        "  note: >-",
        "    The order in which the Hafs text writes marks on a letter; a pair seen in both",
        "    orders takes the majority, and the letters written the other way are exceptions.",
        f"  order: [{_cps(order)}]",
        "  exceptions:",
    ]
    lines += [f'    - {{letter: "{lid}", marks: [{_cps(ms)}]}}' for lid, ms in exceptions]
    if not exceptions:
        lines[-1] = "  exceptions: []"
    lines += [
        "# What each sign means (D72 level b) is added row by row with a citation (G-226).",
        "signs: []",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    cmd = argv[0] if argv else ""
    if cmd == "write":
        Path(OUT).parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(render(), encoding="utf-8")
        print(f"corpus_dabt: wrote {OUT.relative_to(corpus_words.REPO)}")
        return 0
    if cmd == "check":
        ok = OUT.is_file() and OUT.read_text(encoding="utf-8") == render()
        print("corpus_dabt: current" if ok else "corpus_dabt: STALE, run write")
        return 0 if ok else 1
    print("usage: python -m pipeline.corpus_dabt write|check", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
