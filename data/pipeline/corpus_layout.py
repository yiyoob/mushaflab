"""M1.3: corpus/adad/kufi.tsv and corpus/layouts/uthmani-1441h/ from the legacy tables.

Nothing here is typed: every value is copied from tracked, pinned-derived files (rule 1).

- Ayah counting: from the Hafs spine (data/spine/hafs/v1), which holds the KFGQPC Hafs v2.0
  text with its own ayah ends. The Kufi count is the one that text uses. A row's range runs from
  the ayah's first to its last `word` item: a position-0 hizb sign and the ayah-end marker are
  not part of the counted text (the marker is how a printing shows the boundary, and another
  counting system ends ayahs where Hafs has no marker).
- Layout: data/layouts/uthmani-1441h.json (QUL's KFGQPC V4 1441H layout, ingested by
  pipeline.ingest_layout with the owner's print-check corrections, G-011), line for line.

    python -m pipeline.corpus_layout write   # regenerate the tables
    python -m pipeline.corpus_layout check   # exit 1 if a tracked table is not current
"""

import json
import sys
from pathlib import Path

from pipeline import spine

REPO = Path(__file__).resolve().parents[2]
LAYOUT_ID = "uthmani-1441h"
LEGACY_LAYOUT = REPO / "data" / "layouts" / f"{LAYOUT_ID}.json"
LEGACY_CORRECTIONS = REPO / "data" / "layouts" / f"{LAYOUT_ID}.corrections.json"
RENDER_PROFILE = REPO / "data" / "render" / f"hafs-{LAYOUT_ID}.json"
ADAD_OUT = REPO / "corpus" / "adad" / "kufi.tsv"
LAYOUT_DIR = REPO / "corpus" / "layouts" / LAYOUT_ID
LINES_OUT = LAYOUT_DIR / "lines.tsv"
LAYOUT_YAML = LAYOUT_DIR / "layout.yaml"
ADAD_HEADER = ["surah", "ayah", "first_word", "last_word", "source", "status"]
LINES_HEADER = ["page", "line", "type", "first_word", "last_word", "centered"]


def _rel(p: Path) -> str:
    return p.relative_to(REPO).as_posix()


def _items() -> list[dict]:
    with spine.ITEMS.open(encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def ayahs() -> list[tuple[int, int, str, str, str]]:
    """(surah, ayah, first word, last word, ayah-end item id) per ayah, in text order."""
    out: list[tuple[int, int, str, str, str]] = []
    words: list[str] = []
    for it in _items():
        if it["kind"] == "word":
            words.append(it["id"])
        elif it["kind"] == "ayah_end":
            s, a, _ = it["id"].split(":")
            if not words or any(w.split(":")[:2] != [s, a] for w in words):
                msg = f"{it['id']}: ayah end without words of its own ayah"
                raise ValueError(msg)
            out.append((int(s), int(a), words[0], words[-1], it["id"]))
            words = []
    if words:
        msg = f"words after the last ayah end: {words[0]}"
        raise ValueError(msg)
    return out


def render_adad() -> str:
    m = json.loads(spine.MANIFEST.read_text(encoding="utf-8"))
    src = m["source"]
    lines = [
        "# Ayah boundaries, Kufi count (docs/formats.md): the count of the KFGQPC Hafs text.",
        f"# From data/spine/hafs/v1 (spine_version {m['spine_version']}), built from "
        f"{src['id']} member {src['member']} (sha256 {src['sha256']}).",
        "# A range runs from the ayah's first to its last word item; the source names the",
        "# ayah-end item that closes it.",
        "# Generated by `python -m pipeline.corpus_layout write`. Do not edit.",
        "\t".join(ADAD_HEADER),
    ]
    for s, a, first, last, end in ayahs():
        row = [str(s), str(a), first, last, f"kfgqpc-hafs:{end}", "raw-derived"]
        lines.append("\t".join(row))
    return "\n".join(lines) + "\n"


def _legacy() -> dict:
    return json.loads(LEGACY_LAYOUT.read_text(encoding="utf-8"))


def render_lines() -> str:
    d = _legacy()
    lines = [
        f"# Lines of the {LAYOUT_ID} layout (docs/formats.md); provenance in layout.yaml.",
        f"# Converted line for line from {_rel(LEGACY_LAYOUT)}.",
        "# Generated by `python -m pipeline.corpus_layout write`. Do not edit.",
        "\t".join(LINES_HEADER),
    ]
    for ln in d["lines"]:
        text = ln["type"] == "text"
        if text != ("first" in ln and "last" in ln):
            msg = f"page {ln['page']} line {ln['line']}: word range does not match its type"
            raise ValueError(msg)
        row = [
            str(ln["page"]),
            str(ln["line"]),
            ln["type"],
            ln.get("first", ""),
            ln.get("last", ""),
            "true" if ln["centered"] else "false",
        ]
        lines.append("\t".join(row))
    return "\n".join(lines) + "\n"


def _q(s: str) -> str:
    """A YAML double-quoted scalar (JSON strings are valid YAML)."""
    return json.dumps(s, ensure_ascii=False)


def render_layout_yaml() -> str:
    d = _legacy()
    corr = json.loads(LEGACY_CORRECTIONS.read_text(encoding="utf-8"))
    prof = json.loads(RENDER_PROFILE.read_text(encoding="utf-8"))
    out = [
        f"# The {LAYOUT_ID} layout (docs/formats.md). Generated by",
        "# `python -m pipeline.corpus_layout write` from the legacy layout, its corrections and",
        "# the Hafs render profile. Do not edit.",
        f"layout_id: {d['layout_id']}",
        f"script_id: {d['script_id']}",
        "edition: KFGQPC Madinah mushaf, 15 lines, 1441H print",
        f"pages: {d['pages']}",
        f"lines_per_page: {d['lines_per_page']}",
        "writing_style: kfgqpc-madinah",
        f"font: {_q(prof['font'])}",
        f"render_profile: {_q(_rel(RENDER_PROFILE))}",
        "sources:",
        "  - source: qul-layout-1441h",
        f"    pins: {{layout: {d['sources']['layout']}, words: {d['sources']['words']}}}",
        f"    via: {_q(_rel(LEGACY_LAYOUT))}",
        "    status: raw-derived",
        "corrections:",
    ]
    for c in corr["corrections"]:
        out += [
            f"  - page: {c['page']}",
            f"    line: {c['line']}",
            f"    end: {c['end']}",
            f"    was: {_q(c['expect'])}",
            f"    set: {_q(c['set'])}",
            f"    evidence: {_q(c['evidence'])}",
            f"    via: {_q(_rel(LEGACY_CORRECTIONS))}",
        ]
    return "\n".join(out) + "\n"


OUTPUTS = {
    ADAD_OUT: render_adad,
    LINES_OUT: render_lines,
    LAYOUT_YAML: render_layout_yaml,
}


def main(argv: list[str]) -> int:
    cmd = argv[0] if argv else ""
    if cmd == "write":
        for path, fn in OUTPUTS.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(fn(), encoding="utf-8")
            print(f"corpus_layout: wrote {_rel(path)}")
        return 0
    if cmd == "check":
        stale = [p for p, fn in OUTPUTS.items() if not p.is_file() or p.read_text("utf-8") != fn()]
        for p in stale:
            print(f"corpus_layout: STALE {_rel(p)}, run write")
        if not stale:
            print("corpus_layout: current")
        return 1 if stale else 0
    print("usage: python -m pipeline.corpus_layout write|check", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
