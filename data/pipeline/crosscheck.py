"""T1.6: independent cross-check of the Hafs spine against Tanzil Uthmani 1.1.

    python -m pipeline.crosscheck   # write docs/review/hafs-crosscheck.html

Per ayah, words are compared by letter skeleton (normalize.skeleton, so encoding and mark
conventions are ignored). A difference is "spacing" if the letters agree once spaces are
ignored, otherwise "letters". Every difference is listed for the owner to adjudicate.
"""

import html
import sys
from pathlib import Path

from pipeline import sources, spine
from pipeline.normalize import skeleton

REPORT = Path(__file__).resolve().parents[2] / "docs" / "review" / "hafs-crosscheck.html"
HIZB = "\u06de"


def compare(spine_words: list[str], tanzil_words: list[str]) -> str | None:
    a = [skeleton(w) for w in spine_words]
    b = [skeleton(w) for w in tanzil_words]
    if a == b:
        return None
    return "spacing" if "".join(a) == "".join(b) else "letters"


def spine_words_by_ayah() -> dict[tuple[int, int], list[str]]:
    ayahs: dict[tuple[int, int], list[str]] = {}
    for r in spine.load_records():
        s, a, _ = (int(x) for x in r["id"].split(":"))
        words = ayahs.setdefault((s, a), [])
        if r["kind"] == "word":
            words.append("".join(spine.from_cps(c["cps"]) for c in r["clusters"]))
    return ayahs


def tanzil_words_by_ayah() -> dict[tuple[int, int], list[str]]:
    raw = sources.tanzil_ayahs()
    basmalah = [skeleton(w) for w in raw[(1, 1)].split(" ")]
    ayahs = {}
    for (s, a), text in raw.items():
        words = [w for w in text.split(" ") if w and w != HIZB]
        # Tanzil prefixes ayah 1 of most surahs with the basmalah; detected from its own 1:1.
        if s != 1 and a == 1 and [skeleton(w) for w in words[: len(basmalah)]] == basmalah:
            words = words[len(basmalah) :]
        ayahs[(s, a)] = words
    return ayahs


def build_report() -> dict:
    mine, theirs = spine_words_by_ayah(), tanzil_words_by_ayah()
    differences = []
    for key in sorted(mine):
        if key not in theirs:
            differences.append({"ayah": f"{key[0]}:{key[1]}", "category": "missing in Tanzil"})
            continue
        category = compare(mine[key], theirs[key])
        if category:
            differences.append(
                {
                    "ayah": f"{key[0]}:{key[1]}",
                    "category": category,
                    "spine": mine[key],
                    "tanzil": theirs[key],
                }
            )
    return {
        "ayahs_in_spine": len(mine),
        "ayahs_compared": sum(1 for k in mine if k in theirs),
        "extra_in_tanzil": sorted(set(theirs) - set(mine)),
        "differences": differences,
    }


def write_html(report: dict) -> None:
    rows = []
    for d in report["differences"]:
        spine_text = html.escape(" | ".join(d.get("spine", [])))
        tanzil_text = html.escape(" | ".join(d.get("tanzil", [])))
        rows.append(
            f"<tr><td>{d['ayah']}</td><td>{d['category']}</td>"
            f'<td dir="rtl" lang="ar">{spine_text}</td>'
            f'<td dir="rtl" lang="ar">{tanzil_text}</td></tr>'
        )
    page = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width">
<title>Hafs cross-check</title>
<style>
body {{ font-family: system-ui, sans-serif; margin: 2rem; max-width: 70rem; }}
table {{ border-collapse: collapse; width: 100%; }}
td, th {{ border: 1px solid #ccc; padding: .4rem .6rem; vertical-align: top; }}
td[lang=ar] {{ font-size: 1.4rem; font-family: "Amiri Quran", "Scheherazade New", serif; }}
</style></head><body>
<h1>\u1e24af\u1e63 spine vs Tanzil Uthmani 1.1</h1>
<p>Generated by <code>python -m pipeline.crosscheck</code>. Words are compared by letter skeleton
(<code>pipeline/normalize.py</code>), so mark and encoding conventions are ignored.
Ayahs in spine: {report["ayahs_in_spine"]}; compared: {report["ayahs_compared"]};
extra in Tanzil: {len(report["extra_in_tanzil"])}; differences: {len(report["differences"])}.
"spacing" means the same letters split into words differently; "letters" means different letters.
Words are separated by <code>|</code>.</p>
<table><thead><tr>
<th>Ayah</th><th>Kind</th><th>Spine (KFGQPC v2.0)</th><th>Tanzil 1.1</th>
</tr></thead>
<tbody>
{chr(10).join(rows)}
</tbody></table></body></html>
"""
    REPORT.write_text(page, encoding="utf-8")


def main(argv: list[str]) -> int:
    del argv
    report = build_report()
    write_html(report)
    cats = [d["category"] for d in report["differences"]]
    print(f"crosscheck: {report['ayahs_compared']} ayahs compared, differences {cats}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
