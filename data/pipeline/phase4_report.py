"""T4.7: statistics on the raw patches, per riwayah (docs/review/phase4/stats.md).

    python -m pipeline.phase4_report stats    # print
    python -m pipeline.phase4_report write    # write docs/review/phase4/stats.md

Counts are by op, by change shape (`bucket`) and by surah, and by difference kind with its
rule (D21). The last section lists, as evidence for the owner, every Hafs codepoint that a
riwayah's text never uses, with what it corresponds to in the aligned clusters: candidates
for owner-confirmed rows in `data/approvals/difference_kinds.yaml`, never applied automatically.
Ayah-number signs are left out: their changes have their own rule (`ayah-number`).
"""

import sys
from collections import Counter, defaultdict
from pathlib import Path

from pipeline import classify, emit_patches, ingest_riwayah
from pipeline.clusterize import clusterize
from pipeline.codepoints import load_table
from pipeline.differ import Change, pair_clusters
from pipeline.spine import from_cps

REPORT_PATH = Path(__file__).resolve().parents[2] / "docs" / "review" / "phase4" / "stats.md"
BUCKETS = ("mark-only", "letter", "word", "separator", "ayah-number", "hizb")
OPS = ("set_marks", "replace", "delete", "insert_before", "insert_after")
MIN_EVIDENCE = 10  # codepoints with fewer aligned occurrences are not listed (noise)


def bucket(c: Change) -> str:
    """mark-only: same base letter, marks differ; letter: a base letter or a whole cluster
    changes inside a word (a consonant-level change); word: a word inserted or deleted."""
    if c.item_kind == "ayah_end":
        return "ayah-number"
    if c.item_kind == "hizb":
        return "hizb"
    if c.kind == "separator":
        return "separator"
    if c.kind in ("item-insert", "item-delete"):
        return "word"
    return "mark-only" if c.kind == "marks" else "letter"


def _cp(c: str) -> str:
    return f"U+{ord(c):04X}"


def evidence(riwayah: str) -> list[tuple[str, int, list[tuple[str, int]]]]:
    """Hafs codepoints absent from the riwayah's text: (cp, aligned occurrences, fates)."""
    pairs, _ = emit_patches.derive(riwayah)
    _, recs = emit_patches.hafs()
    table = load_table()
    used = set("".join(i.text for i in ingest_riwayah.load(riwayah).items))
    occ: Counter = Counter()
    fate: dict[str, Counter] = defaultdict(Counter)
    for p in pairs:
        if not (p.h and p.r) or p.h.kind == "ayah_end":
            continue
        hs = [(c["id"], c["kind"], from_cps(c["cps"])) for c in recs[p.h.ref]["clusters"]]
        for h, c in pair_clusters(hs, clusterize(p.r.text, table)):
            if not (h and c):
                continue
            absent = [x for x in h[2] if x not in used]
            if not absent:
                continue
            comps = classify.components(h[2], c.text)
            subs = {x: y for t, x, y in comps if t == "sub"}
            for x in absent:
                occ[x] += 1
                fate[x]["U+" + f"{ord(subs[x]):04X}" if x in subs else "other change"] += 1
    return [
        (_cp(x), n, fate[x].most_common(3))
        for x, n in sorted(occ.items(), key=lambda kv: -kv[1])
        if n >= MIN_EVIDENCE
    ]


def _table(header: list[str], rows: list[list[object]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return out + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]


def report() -> str:
    confirmed = classify.load_confirmed()
    per: dict[str, list[Change]] = {r: emit_patches.changes_for(r) for r in emit_patches.ORDER}
    lines = [
        "# Raw patch statistics (T4.7)",
        "",
        "Generated by `python -m pipeline.phase4_report write` from the same derivation as"
        " `data/patches/raw/` (one change = one patch). Buckets: **mark-only** (same base"
        " letter, marks differ), **letter** (a base letter or a whole cluster inside a word"
        " changes, inserted or deleted), **word** (a word inserted or deleted), **separator**,"
        " **ayah-number** (anything in an ayah-end item), **hizb**. Every patch is"
        " `raw-derived` and `single_source`. Buckets describe the edit, not its cause.",
        "",
        "## By bucket",
        "",
    ]
    lines += _table(
        ["Riwayah", "Patches", *BUCKETS],
        [
            [r, len(cs), *(Counter(bucket(c) for c in cs)[b] for b in BUCKETS)]
            for r, cs in per.items()
        ],
    )
    lines += ["", "## By op", ""]
    lines += _table(
        ["Riwayah", *OPS, "item ops", "cluster ops"],
        [
            [
                r,
                *(Counter(c.op for c in cs)[o] for o in OPS),
                sum(1 for c in cs if c.level == "item"),
                sum(1 for c in cs if c.level == "cluster"),
            ]
            for r, cs in per.items()
        ],
    )
    lines += ["", "## By difference kind (D21)", ""]
    lines += _table(
        ["Riwayah", "Kind", "Rule", "Patches"],
        [
            [r, kind, rule, n]
            for r, cs in per.items()
            for (kind, rule), n in sorted(
                Counter(
                    (t.kind, t.rule) for t in (classify.classify(c, confirmed[r]) for c in cs)
                ).items()
            )
        ],
    )
    lines += ["", "## By surah", ""]
    for r, cs in per.items():
        by_surah: dict[int, Counter] = defaultdict(Counter)
        for c in cs:
            by_surah[c.surah][bucket(c)] += 1
        lines += ["<details>", f"<summary>{r}</summary>", ""]
        lines += _table(
            ["Surah", *BUCKETS, "Total"],
            [
                [s, *(by_surah[s][b] for b in BUCKETS), sum(by_surah[s].values())]
                for s in sorted(by_surah)
            ],
        )
        lines += ["", "</details>", ""]
    lines += [
        "## Evidence for D21: Hafs codepoints a riwayah never uses",
        "",
        "For each Hafs codepoint that does not occur anywhere in the riwayah's text (and has at"
        f" least {MIN_EVIDENCE} aligned occurrences): how often it occurs in aligned clusters,"
        " and what the riwayah has at the same position (a one-for-one substitution) or"
        " 'other change' (part of a larger change). This is evidence only: whether a"
        " substitution is an encoding, spelling or reading difference is the owner's call"
        " (D21), recorded as a confirmed row before any tag changes.",
        "",
    ]
    for r in emit_patches.ORDER:
        rows = [[cp, n, "; ".join(f"{k} x{m}" for k, m in fates)] for cp, n, fates in evidence(r)]
        lines += [f"### {r}", ""]
        lines += _table(["Hafs codepoint", "Aligned occurrences", "Riwayah has (top 3)"], rows)
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = report()
    if argv[1:] == ["write"]:
        REPORT_PATH.write_text(text, encoding="utf-8")
        print(f"stats written to {REPORT_PATH}")
        return 0
    if argv[1:] == ["check"]:
        ok = REPORT_PATH.exists() and REPORT_PATH.read_text(encoding="utf-8") == text
        print("stats: " + ("up to date" if ok else "stale"))
        return 0 if ok else 1
    print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
