"""T4.6: version drift between pinned KFGQPC releases (and QUL for Warsh), for review.

    python -m pipeline.drift write     # docs/review/phase4/version-drift.md

For each riwayah with both: the official v2.x text against the 2022 mirror, ayah by ayah;
for Warsh also the official text against QUL's `qpc-warsh` word list (sourced from KFGQPC,
so not independent, T0.2). Differences are reported as codepoint changes, grouped by the
same change; nothing is judged. These catch version drift and transcription slips, not
reading errors (PROJECT_PLAN T4.6).
"""

import difflib
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

from pipeline import ingest_riwayah, kfgqpc, sources

REPORT_PATH = (
    Path(__file__).resolve().parents[2] / "docs" / "review" / "phase4" / "version-drift.md"
)
WITH_MIRROR = ("hafs", "shuba", "warsh", "qalun", "qunbul", "duri_abuamr", "susi")
QUL_WARSH = "qul-script-qpc-warsh-wbw"
SHOWN = 12


def _cps(s: str) -> str:
    return " ".join(f"U+{ord(c):04X}" for c in s) or "nothing"


def changes(a: str, b: str) -> tuple[str, ...]:
    """Codepoint-level changes from a to b, as readable strings."""
    out = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if tag != "equal":
            out.append(f"{_cps(a[i1:i2])} -> {_cps(b[j1:j2])}")
    return tuple(out)


def _key(row: dict) -> tuple[int, int]:
    surah = row.get("sura_no", row.get("sora"))
    return int(surah), int(row["aya_no"])  # type: ignore[arg-type]


def compare(a: dict[tuple[int, int], str], b: dict[tuple[int, int], str]) -> dict:
    """Ayahs only in one side, and differing ayahs grouped by their codepoint changes."""
    grouped: dict[tuple[str, ...], list[tuple[int, int]]] = defaultdict(list)
    for k in sorted(a.keys() & b.keys()):
        if a[k] != b[k]:
            grouped[changes(a[k], b[k])].append(k)
    return {
        "only_a": sorted(a.keys() - b.keys()),
        "only_b": sorted(b.keys() - a.keys()),
        "grouped": grouped,
        "differing": sum(len(v) for v in grouped.values()),
        "common": len(a.keys() & b.keys()),
    }


def _section(title: str, a_name: str, b_name: str, result: dict) -> list[str]:
    lines = [f"## {title}", ""]
    lines.append(
        f"{result['common']} ayahs in both; {result['differing']} differ;"
        f" only in {a_name}: {len(result['only_a'])}; only in {b_name}: {len(result['only_b'])}."
    )
    if result["grouped"]:
        lines += ["", f"| Ayahs | Count | Change ({a_name} -> {b_name}) |", "|---|---|---|"]
        ordered = sorted(result["grouped"].items(), key=lambda kv: (-len(kv[1]), kv[1]))
        for change, keys in ordered:
            shown = ", ".join(f"{s}:{n}" for s, n in keys[:SHOWN])
            more = f" (+{len(keys) - SHOWN} more)" if len(keys) > SHOWN else ""
            lines.append(f"| {shown}{more} | {len(keys)} | {'; '.join(change)} |")
    return [*lines, ""]


def words_without_number(text: str) -> str:
    """The ayah's words joined by single spaces (separators and the ayah number dropped)."""
    tokens = [t for t in re.split("[ \u00a0]+", text) if t]
    if tokens and ingest_riwayah.is_ayah_number(tokens[-1]):
        tokens = tokens[:-1]
    elif tokens and ingest_riwayah.is_ayah_number(tokens[-1][-1]):
        tokens[-1] = tokens[-1][:-1]
    return " ".join(tokens)


def by_value(text: str) -> tuple[str, str]:
    """The text with its trailing ayah number written as `[n]`, and how the number was written
    (`sign` or `digits`), so files that encode numbers differently compare by value."""
    m = re.search("([\ufc00-\ufdff]|[\u0660-\u0669]+)$", text)
    if not m:
        return text, "none"
    style = "sign" if len(m.group(1)) == 1 and m.group(1) >= "\ufc00" else "digits"
    return text[: m.start()] + f"[{ingest_riwayah.decode_ayah_number(m.group(1))}]", style


def report() -> str:
    lines = [
        "# Version drift (T4.6)",
        "",
        "Generated by `python -m pipeline.drift write` from pinned sources. Each section compares"
        " two releases ayah by ayah and groups differing ayahs by their codepoint changes. These"
        " are differences between files, reported as found; they are not judged here.",
        "",
        "Bazzi: only the 2022 mirror v7 is pinned (D13), so there is nothing to compare.",
        "",
    ]
    lines += [
        "Ayah numbers are compared by value: `[n]` stands for the number, whether a file writes it"
        " as a U+FC00+n-1 sign or as Arabic-Indic digits. How each file writes them is counted"
        " per section.",
        "",
    ]
    for r in WITH_MIRROR:
        mirror_rows = sources.json_file(f"kfgqpc-mirror-{r}-data")
        sides = []
        for rows in (kfgqpc.rows(r), mirror_rows):
            values = {_key(row): by_value(row["aya_text"]) for row in rows}  # type: ignore[union-attr]
            sides.append(values)
        styles = [Counter(v[1] for v in side.values()) for side in sides]
        official, mirror = ({k: v[0] for k, v in side.items()} for side in sides)
        sid = kfgqpc.source_id(r)
        section = _section(
            f"{r}: official ({sid}) vs 2022 mirror", "official", "mirror", compare(official, mirror)
        )
        section.insert(
            3,
            f"Ayah numbers written as: official {dict(sorted(styles[0].items()))},"
            f" mirror {dict(sorted(styles[1].items()))}.",
        )
        section.insert(4, "")
        lines += section
    qul: dict[tuple[int, int], list[str]] = defaultdict(list)
    words = sources.zip_json(QUL_WARSH, ".json")
    for w in sorted(words.values(), key=lambda w: int(w["id"])):  # type: ignore[union-attr]
        if not ingest_riwayah.is_ayah_number(w["text"]):
            qul[(int(w["surah"]), int(w["ayah"]))].append(w["text"])
    official = {_key(row): words_without_number(row["aya_text"]) for row in kfgqpc.rows("warsh")}
    joined = {k: " ".join(v) for k, v in qul.items()}
    lines += _section(
        "warsh: official words vs QUL qpc-warsh words (separators and ayah numbers ignored)",
        "official",
        "QUL",
        compare(official, joined),
    )
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = report()
    if argv[1:] == ["write"]:
        REPORT_PATH.write_text(text, encoding="utf-8")
        print(f"version drift report written to {REPORT_PATH}")
        return 0
    print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
