"""T5.5: the GATE G3 review index, `docs/review/phase5/README.md`.

    python -m pipeline.phase5_readme write   # rebuild the index from the tracked reports
    python -m pipeline.phase5_readme check   # exit 1 if it is stale

The index gathers, per riwayah, the numbers of the layout reports (`layout-<r>.md`, written by
`mushaf-fitlines`) and the overflow reports (`overflow-<r>.md`, written by `just golden`), and
says where the contact sheets are (`just contact-sheets`, untracked images).
"""

import re
import sys
from pathlib import Path

REVIEW = Path(__file__).resolve().parents[2] / "docs" / "review" / "phase5"
INDEX = REVIEW / "README.md"
RIWAYAT = ("hafs", "shuba", "warsh", "qalun", "bazzi", "qunbul", "duri_abuamr", "susi")
NATIVE = RIWAYAT[1:]
PAGES, PER_SHEET = 604, 24


def _cell(text: str, label: str) -> str:
    m = re.search(rf"^\| {re.escape(label)} \| ([^|]+) \|$", text, re.MULTILINE)
    if not m:
        raise ValueError(f"no row {label!r}")
    return m.group(1).strip()


def summary(riwayah: str) -> dict[str, str]:
    lay = (REVIEW / f"layout-{riwayah}.md").read_text(encoding="utf-8")
    ov = (REVIEW / f"overflow-{riwayah}.md").read_text(encoding="utf-8")
    short = re.search(r"^## Short lines \((\d+), P5\)$", lay, re.MULTILINE)
    return {
        "forced": _cell(lay, "forced"),
        "hafs": _cell(lay, "hafs"),
        "fitted": _cell(lay, "fitted"),
        "short": short.group(1) if short else "?",
        "blocked": _cell(ov, "Pages blocked (G-102)"),
        "scaled": _cell(ov, "Pages scaled below 1"),
        "floor": _cell(ov, "Pages at the scale floor"),
        "squeezed": _cell(ov, "Squeezed lines"),
        "space": _cell(ov, "Widest space per line, median / p95 / max (x normal)"),
        "g045": _cell(ov, "Spacing upright alef after a non-joining letter (G-045)"),
    }


def render() -> str:
    sheets = (PAGES + PER_SHEET - 1) // PER_SHEET
    out = [
        "# GATE G3 review: Phase 5, all 8 riwayat\n",
        "Generated by `python -m pipeline.phase5_readme write` from the tracked reports in this "
        "folder. Nothing here is a claim about the readings: the pages draw what the pinned "
        "KFGQPC data say (all non-Hafs texts are single-source, D13).\n",
        "## What to review\n",
        "1. **Contact sheets** (`just contact-sheets`, then open `docs/review/phase5/contact/`): "
        f"`<riwayah>-NN.png`, {sheets} sheets per riwayah, {PER_SHEET} pages each, right to left "
        "as a mushaf is read; sheet NN holds pages 24 x (NN - 1) + 1 to 24 x NN. A grey tile "
        "with a cross is a page that cannot be drawn until its encoding groups are decided "
        "(G-102); a red frame marks a page with a pinned rule-6 finding (G-101, G-103). Render "
        "any page large with `just render PAGE=<n> RIWAYAH=<id>`.\n",
        "2. **Line breaks (D29, D1 final form)**: `layout-<r>.md` lists every line fitted by "
        "width; every other open break takes the 1441H Hafs break (G-104, a hypothesis until "
        "the spot check, G-106).\n",
        "3. **Overflow (D31)**: `overflow-<r>.md`, every scaled page and squeezed line.\n",
        "**Print spot check (G-106, 2026-10-23).** Shu\u02bfbah pages 7, 300 and 501 match the "
        "QuranFlash `Shubah` scan at every word break (apart from the ayah-marker convention "
        "accepted for Hafs, D6 addendum). Warsh and Qalun could not be verified: the only "
        "Warsh scan with KFGQPC's page frame (`Warsh2`) is another printing, and on its page 8 "
        "2 of 9 transferred breaks differ (a warning, not proof; G-104). No scans exist for "
        "Bazzi, Qunbul or al-Susi; the `Douri` book is another printing. Fitted lines (G-105) "
        "have no verdict. The reference still needed is KFGQPC's own Warsh/Qalun printing.\n",
        "4. **Decisions waiting**: D29, D30 (short lines: 60% threshold on evidence), D32, D33 "
        "(display style as a render key, default style only); the "
        "open encoding groups (G-102, sheet `build/review/phase5/encoding.html` from "
        "`just review-phase5`); G-103; G-101.\n",
        "## Per riwayah\n",
        "| Riwayah | forced | hafs | fitted | short | blocked pages | scaled | at floor | "
        "squeezed | widest space (median / p95 / max) | G-045 |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
        "| hafs | (1441H layout, D6) | | | 30 | 0 | 209 | 32 | 65 | 2.85 / 3.79 / 5.87 | 1377 |",
    ]
    for r in NATIVE:
        s = summary(r)
        out.append(
            f"| {r} | {s['forced']} | {s['hafs']} | {s['fitted']} | {s['short']} | "
            f"{s['blocked']} | {s['scaled']} | {s['floor']} | {s['squeezed']} | {s['space']} | "
            f"{s['g045']} |"
        )
    out.append("")
    out.append("Hafs numbers are from the GATE G1 record (D15); Hafs's own reports are in "
               "`docs/review/phase3-g1.md`.\n")  # fmt: skip
    return "\n".join(out)


def main(argv: list[str]) -> int:
    cmd = argv[1] if len(argv) > 1 else "write"
    text = render()
    if cmd == "write":
        INDEX.write_text(text, encoding="utf-8")
        return 0
    if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != text:
        print("phase5_readme: docs/review/phase5/README.md differs from a rebuild", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
