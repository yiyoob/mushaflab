"""T4.2: ayah maps per riwayah (PROJECT_PLAN 3.4), derived from the alignment and the differ.

    python -m pipeline.ayah_maps write   # data/ayah_maps/*.yaml, docs/review/phase4/ayah-maps.md
    python -m pipeline.ayah_maps check   # exit 1 if a tracked file is stale

An entry maps the riwayah's own (surah, ayah), as numbered in its KFGQPC file, to the first
and last resolved items of that ayah: spine ids, or inserted ids (`<anchor>+ins.<seq>`) for
items the spine lacks. The round-trip (T4.6) checks every entry against the KFGQPC text.

The findings report compares numbering with Hafs through the aligned words only. Statements
about the Quran that do not come from the pinned data are hypotheses and are labelled so.
"""

import sys
from itertools import groupby
from pathlib import Path

from pipeline import emit_patches, ingest_riwayah
from pipeline.align import Pair
from pipeline.differ import Change
from pipeline.emit_patches import flow

MAP_DIR = Path(__file__).resolve().parents[1] / "ayah_maps"
REPORT_PATH = Path(__file__).resolve().parents[2] / "docs" / "review" / "phase4" / "ayah-maps.md"

Key = tuple[int, int]


def path_for(riwayah: str) -> Path:
    return MAP_DIR / f"{riwayah}.yaml"


def resolved_ids(pairs: list[Pair], changes: list[Change]) -> dict[str, str]:
    """Riwayah item ref -> the id of that item in the resolved text."""
    ids = {p.r.ref: p.h.ref for p in pairs if p.r and p.h}
    ids |= {c.ref: c.key for c in changes if c.kind == "item-insert"}
    return ids


def entries(riwayah: str) -> list[dict]:
    pairs, changes = emit_patches.derive(riwayah)
    ids = resolved_ids(pairs, changes)
    items = ingest_riwayah.load(riwayah).items
    out = []
    for (s, a), group in groupby(items, key=lambda i: (i.surah, i.ayah)):
        g = list(group)
        out.append({"surah": s, "ayah": a, "first": ids[g[0].ref], "last": ids[g[-1].ref]})
    return out


def render_map(riwayah: str) -> str:
    lines = [
        f"# Ayah map for {riwayah}: its own numbering -> resolved items on the Hafs spine.",
        "# Generated by `python -m pipeline.ayah_maps write` (T4.2). Do not edit.",
        f"riwayah: {flow(riwayah)}",
        f"spine: {flow(emit_patches.SPINE_ID)}",
        "entries:",
    ]
    lines += ["  - " + flow(e) for e in entries(riwayah)]
    return "\n".join(lines) + "\n"


# --- numbering findings -------------------------------------------------------------------


def hafs_ayahs(riwayah: str) -> dict[Key, list[Key]]:
    """For each riwayah ayah, the Hafs ayahs of its aligned words, in order, without repeats."""
    pairs, _ = emit_patches.derive(riwayah)
    out: dict[Key, list[Key]] = {}
    for p in pairs:
        if p.r is None:
            continue
        cover = out.setdefault((p.r.surah, p.r.ayah), [])
        if p.h is not None and p.h.kind == "word" and (p.h.surah, p.h.ayah) not in cover:
            cover.append((p.h.surah, p.h.ayah))
    return out


def _last_words(items: list[ingest_riwayah.Item]) -> set[str]:
    """Refs of the last word of every ayah: an ayah boundary falls right after each."""
    last: dict[Key, str] = {}
    for i in items:
        if i.kind == "word":
            last[(i.surah, i.ayah)] = i.ref
    return set(last.values())


def findings(riwayah: str) -> dict:
    """Ayah boundaries compared after aligned words, numbering shifts, uncovered ayahs."""
    pairs, _ = emit_patches.derive(riwayah)
    hafs_last = _last_words(ingest_riwayah.load("hafs").items)
    riw_last = _last_words(ingest_riwayah.load(riwayah).items)
    only_hafs, only_riw, unpaired = [], [], []
    for p in pairs:
        h = p.h if p.h and p.h.kind == "word" else None
        r = p.r if p.r and p.r.kind == "word" else None
        if h and r:
            if (h.ref in hafs_last) != (r.ref in riw_last):
                (only_hafs if h.ref in hafs_last else only_riw).append((h.ref, r.ref))
        elif h and h.ref in hafs_last:
            unpaired.append(("Hafs", h.ref))
        elif r and r.ref in riw_last:
            unpaired.append((riwayah, r.ref))
    cover = hafs_ayahs(riwayah)
    used = {h for hs in cover.values() for h in hs}
    hafs_all = [
        (i.surah, i.ayah) for i in ingest_riwayah.load("hafs").items if i.kind == "ayah_end"
    ]
    runs: list[tuple[int, int, int, int]] = []  # surah, first, last, offset (hafs - riwayah)
    for r, hs in cover.items():
        if len(hs) != 1 or hs[0][1] == r[1]:
            continue
        off = hs[0][1] - r[1]
        if runs and runs[-1][0] == r[0] and runs[-1][2] == r[1] - 1 and runs[-1][3] == off:
            runs[-1] = (r[0], runs[-1][1], r[1], off)
        else:
            runs.append((r[0], r[1], r[1], off))
    return {
        "ayahs": len(cover),
        "only_hafs": only_hafs,
        "only_riw": only_riw,
        "unpaired": unpaired,
        "uncovered": [h for h in hafs_all if h not in used],
        "shifts": runs,
    }


def _k(k: Key) -> str:
    return f"{k[0]}:{k[1]}"


def _ks(keys: list[Key]) -> str:
    return ", ".join(_k(k) for k in keys)


# Expectations named in PROJECT_PLAN T4.2/T4.8 without a cited source: hypotheses (rule 1).
HYPOTHESES = (
    ("warsh", (1, 4), "PROJECT_PLAN T4.2: 1:4 in Hafs is 1:3 in Warsh"),
    (
        "warsh",
        (3, 133),
        "PROJECT_PLAN T4.8: in 3:133 Warsh drops the initial waw of the first word",
    ),
    (
        "warsh",
        (2, 10),
        "PROJECT_PLAN T4.8: 2:10, Hafs vs Warsh word differences, Warsh numbering shifts",
    ),
    (
        "warsh",
        (2, 184),
        "PROJECT_PLAN T4.8: 2:184, Hafs vs Warsh word differences, Warsh numbering shifts",
    ),
)


def hypothesis_rows() -> list[str]:
    lines = [
        "## Expectations from the plan (hypotheses: not asserted, not tests)",
        "",
        "Each line states what the pinned data shows for a statement the plan makes without a"
        " cited source. They stay **hypothesis** until the owner confirms them against a cited"
        " source (CLAUDE.md rule 1). Owner decision at GATE G2 (2026-10-22): kept as"
        " hypotheses, as documented observations and not tests; revisit when a cited source"
        " is available (G-074).",
        "",
        "| Statement (hypothesis) | What the data shows |",
        "|---|---|",
    ]
    for riwayah, hafs_key, text in HYPOTHESES:
        cover = hafs_ayahs(riwayah)
        holders = [r for r, hs in cover.items() if hafs_key in hs]
        _, changes = emit_patches.derive(riwayah)
        prefix = f"{hafs_key[0]}:{hafs_key[1]}:"
        ops = [c for c in changes if c.target.startswith(prefix) and c.kind != "marks"]
        shown = "; ".join(f"{c.op} {c.target} ({c.kind})" for c in ops[:6]) or "no letter/word ops"
        lines.append(
            f"| {text} | Hafs {_k(hafs_key)} words are in {riwayah} ayah(s)"
            f" {_ks(holders) or 'none'};"
            f" non-mark ops on Hafs {_k(hafs_key)}: {shown} |"
        )
    return [*lines, ""]


def report() -> str:
    lines = [
        "# Ayah maps and numbering findings (T4.2)",
        "",
        "Generated by `python -m pipeline.ayah_maps write`. Each riwayah's ayahs are numbered as"
        " in its pinned KFGQPC file; `data/ayah_maps/<riwayah>.yaml` maps every one of them to"
        " its resolved items, and `just roundtrip` checks each entry against the text.",
        "",
        "Numbering is compared through the word alignment (T4.3): an ayah boundary falls after"
        " the last word of an ayah. Below, a boundary 'only in Hafs' means Hafs ends an ayah"
        " after that aligned word and the riwayah does not (it continues the ayah); 'only in"
        " the riwayah' is the reverse. These are read from the files; what they mean is for"
        " the owner to confirm.",
        "",
        "| Riwayah | Ayahs (from the data) | Boundaries only in Hafs | Only in the riwayah"
        " | At unpaired words | Hafs ayahs with no aligned word |",
        "|---|---|---|---|---|---|",
    ]
    found = {r: findings(r) for r in emit_patches.ORDER}
    for r, f in found.items():
        lines.append(
            f"| {r} | {f['ayahs']} | {len(f['only_hafs'])} | {len(f['only_riw'])}"
            f" | {len(f['unpaired'])} | {_ks(f['uncovered']) or 'none'} |"
        )
    for r, f in found.items():
        lines += ["", f"## {r}", ""]
        rows = [(h, w, "Hafs only") for h, w in f["only_hafs"]]
        rows += [(h, w, f"{r} only") for h, w in f["only_riw"]]
        if rows:
            lines += ["| Hafs word | " + r + " word | Ayah ends after it in |", "|---|---|---|"]
            lines += [f"| {h} | {w} | {where} |" for h, w, where in sorted(rows, key=_order)]
        else:
            lines.append("- Ayah boundaries: same as Hafs at every aligned word")
        for side, ref in f["unpaired"]:
            lines.append(f"- Ayah ends after an unpaired {side} word: {ref}")
        if f["shifts"]:
            lines += ["", "| Surah | Riwayah ayahs | Hafs ayah = riwayah ayah + |", "|---|---|---|"]
            for s_, a, b, off in f["shifts"]:
                span = f"{a}-{b}" if a != b else f"{a}"
                lines.append(f"| {s_} | {span} | {off:+d} |")
        else:
            lines.append("- Numbering shifts: none")
    lines += ["", *hypothesis_rows()]
    return "\n".join(lines)


def _order(row: tuple[str, str, str]) -> tuple[int, ...]:
    return tuple(int(x) for x in row[0].split(":"))


def main(argv: list[str]) -> int:
    files = {path_for(r): render_map(r) for r in emit_patches.ORDER}
    files[REPORT_PATH] = report()
    if argv[1:] == ["write"]:
        MAP_DIR.mkdir(parents=True, exist_ok=True)
        for p, text in files.items():
            p.write_text(text, encoding="utf-8")
        print(f"ayah maps written to {MAP_DIR}, findings to {REPORT_PATH}")
        return 0
    stale = [p.name for p, t in files.items() if not p.exists() or p.read_text("utf-8") != t]
    print("ayah maps: " + (f"stale {stale}" if stale else "up to date"))
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
