"""T6.7/T6.8: style conversion rows and the style-convention report (ADR D44).

    python -m pipeline.style_conversion write   # data/encodings/style-conversion.json
                                                # docs/review/phase6/style-conventions.md
    python -m pipeline.style_conversion check   # exit 1 if either is stale

Display styles (D36): Hijazi (Mashriqi) and Maghribi. The KFGQPC texts encode style-specific
mark conventions in their codepoints (G-006). A conversion row maps one codepoint of one
style's convention to the other's, and is applied only at render time (the spine and the
patches stay codepoint-exact). Rows are never invented: each comes from an owner-confirmed
`encoding` row in `data/approvals/difference_kinds.yaml` (D21) that holds for every riwayah
of the target style. The report lists every codepoint whose use differs between the two
families of KFGQPC texts, with its counts and whether a confirmed row covers it; anything
without evidence stays unconverted.
"""

import json
import sys
from collections import Counter

from pipeline import classify, kfgqpc
from pipeline.compile_db import DATA_ROOT
from pipeline.dk_encoding import cps

OUT = DATA_ROOT / "encodings" / "style-conversion.json"
REPORT = DATA_ROOT.parent / "docs" / "review" / "phase6" / "style-conventions.md"
STYLE_OF = {
    "hafs": "hijazi",
    "shuba": "hijazi",
    "bazzi": "hijazi",
    "qunbul": "hijazi",
    "duri_abuamr": "hijazi",
    "susi": "hijazi",
    "warsh": "maghribi",
    "qalun": "maghribi",
}
BASE_LETTERS = range(0x0621, 0x064B)


def rows() -> list[dict]:
    """Hijazi -> Maghribi rows: confirmed `encoding` rows shared by every Maghribi riwayah."""
    confirmed = classify.load_confirmed()
    maghribi = [r for r, s in STYLE_OF.items() if s == "maghribi"]
    shared = set.intersection(
        *({k for k, kind in confirmed[r].items() if kind == "encoding"} for r in maghribi)
    )
    return [
        {
            "from_style": "hijazi",
            "to_style": "maghribi",
            "from": cps(frm),
            "to": cps(to),
            "evidence": (
                f"data/approvals/difference_kinds.yaml: {', '.join(maghribi)} "
                f"{cps(frm)} -> {cps(to)} (encoding, owner-confirmed, D21)"
            ),
        }
        for frm, to in sorted(shared)
    ]


def table() -> dict:
    return {
        "schema": 1,
        "note": (
            "Style conversion rows (T6.7, D44): applied at render time only, from "
            "owner-confirmed encoding rows. Generated by "
            "`python -m pipeline.style_conversion write`."
        ),
        "rows": rows(),
    }


def usage() -> dict[str, Counter]:
    """Codepoint counts per style family over the KFGQPC texts (excluding base letters)."""
    out: dict[str, Counter] = {"hijazi": Counter(), "maghribi": Counter()}
    for r, style in STYLE_OF.items():
        for row in kfgqpc.rows(r):
            for c in row["aya_text"]:
                if ord(c) not in BASE_LETTERS and not c.isspace():
                    out[style][c] += 1
    return out


def report() -> str:
    u = usage()
    covered = {(r["from"], r["to"]) for r in rows()}
    froms = {f for f, _ in covered}
    tos = {t for _, t in covered}
    lines = [
        "# Style conventions: Hijazi and Maghribi (T6.8, D44)",
        "",
        "Generated by `python -m pipeline.style_conversion write` from the KFGQPC texts",
        "(Hijazi family: hafs, shuba, bazzi, qunbul, duri_abuamr, susi; Maghribi: warsh, qalun).",
        "A codepoint is listed when one family uses it at least ten times as often as the other",
        "(per text). Only owner-confirmed rows convert (D21); every other difference stays",
        "unconverted until the owner confirms a row with evidence.",
        "",
        "| Codepoint | Hijazi uses (6 texts) | Maghribi uses (2 texts) | Conversion |",
        "|---|---|---|---|",
    ]
    for c in sorted(set(u["hijazi"]) | set(u["maghribi"])):
        h, m = u["hijazi"][c] / 6, u["maghribi"][c] / 2
        if not (h >= 10 * max(m, 0.1) or m >= 10 * max(h, 0.1)):
            continue
        cp = f"U+{ord(c):04X}"
        conv = (
            "converted (Hijazi -> Maghribi)"
            if cp in froms
            else ("target of a converted row" if cp in tos else "**unconverted, no evidence**")
        )
        lines.append(f"| {cp} | {u['hijazi'][c]} | {u['maghribi'][c]} | {conv} |")
    lines += [
        "",
        f"Confirmed rows: {len(covered)}. Maghribi -> Hijazi has no row: U+0652 in the Maghribi",
        "texts stands for both Hijazi U+06E1 and U+0652, so the inverse is not determined by the",
        "data.",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    t = json.dumps(table(), ensure_ascii=True, indent=1) + "\n"
    r = report()
    if argv[1:] == ["write"]:
        OUT.write_text(t, encoding="ascii")
        REPORT.parent.mkdir(parents=True, exist_ok=True)
        REPORT.write_text(r, encoding="utf-8")
        return 0
    if argv[1:] == ["check"]:
        ok = OUT.exists() and OUT.read_text(encoding="ascii") == t
        ok = ok and REPORT.exists() and REPORT.read_text(encoding="utf-8") == r
        return 0 if ok else 1
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
