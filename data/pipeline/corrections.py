"""D39: DigitalKhatt rows for owner corrections to the Hafs spine text.

    python -m pipeline.corrections write   # data/encodings/hafs-v1.correction-rows.json
    python -m pipeline.corrections check   # exit 1 if the tracked file is stale

A correction (`patches/corrections/hafs.yaml`) replaces a spine cluster with the form the
owner decided. The renderer converts KFGQPC clusters to DigitalKhatt through the Hafs table
(D14), which has no row for the corrected form. The row is derived, never invented: the
corrected cluster takes the DigitalKhatt image of the spine cluster it replaces, and only
when that image *is* the corrected form (DigitalKhatt's own text writes the word that way).
Anything else is an error.
"""

import json
import sys

from pipeline import dk_encoding, spine
from pipeline.compile_db import DATA_ROOT, load_yaml
from pipeline.dk_encoding import Table, cps

PATCHES = DATA_ROOT / "patches" / "corrections" / "hafs.yaml"
OUT = dk_encoding.ENCODINGS_DIR / "hafs-v1.correction-rows.json"


class CorrectionError(ValueError):
    pass


def rows(patches: list[dict], clusters: dict[str, str], table: Table) -> list[dict]:
    """Encoding rows for the corrected forms; `clusters` maps spine cluster id -> text."""
    out = []
    for p in patches:
        if p["op"] != "replace" or "cps" not in p.get("payload", {}):
            raise CorrectionError(f"{p['id']}: only cluster replacements are supported")
        new = spine.from_cps(p["payload"]["cps"])
        if new in table.cluster_rows:
            continue
        old = clusters[p["target"]]
        image = table.cluster_rows.get(old)
        if image != new:
            raise CorrectionError(
                f"{p['id']}: the DigitalKhatt image of {cps(old)} is "
                f"{cps(image) if image else None}, not the corrected form {cps(new)}"
            )
        out.append(
            {
                "src": [cps(new)],
                "dst": cps(image),
                "kind": "cluster",
                "groups": [f"correction {p['id']}"],
            }
        )
    return out


def build() -> dict:
    table = Table.from_json(json.loads(dk_encoding.TABLE_PATH.read_text(encoding="utf-8")))
    clusters = {
        c["id"]: spine.from_cps(c["cps"]) for r in spine.load_records() for c in r["clusters"]
    }
    patches = load_yaml(PATCHES)["patches"] if PATCHES.exists() else []
    return {
        "schema": 1,
        "spine": "hafs/v1",
        "from": "kfgqpc",
        "to": "digitalkhatt-madina",
        "note": (
            "Rows for the owner's corrections to the Hafs spine (D39), each the DigitalKhatt "
            "image of the corrected spine cluster. Generated by "
            "`python -m pipeline.corrections write`."
        ),
        "rows": rows(patches, clusters, table),
    }


def render() -> str:
    return json.dumps(build(), ensure_ascii=True, indent=1) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if argv[1:] == ["write"]:
        OUT.write_text(text, encoding="ascii")
        return 0
    if argv[1:] == ["check"]:
        return 0 if OUT.exists() and OUT.read_text(encoding="ascii") == text else 1
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
