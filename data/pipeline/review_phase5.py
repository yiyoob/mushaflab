"""T5.3: review sheet for the marks the KFGQPC Warsh and Qalun fonts leave unanchored (G-100).

    python -m pipeline.review_phase5     # build/review/phase5/kfgqpc-rule6.html (untracked)

Reads the pinned list `tests/golden/shape/kfgqpc-rule6-pending.json` (written by `just golden`)
and the resolved texts of `just roundtrip` (`build/roundtrip/<riwayah>.jsonl`), and draws every
listed word large in the riwayah's own KFGQPC font, grouped by the unanchored glyph. The owner
decides per glyph whether its placement matches the print (D27).
"""

import base64
import html
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

from pipeline import kfgqpc, spine

REPO = Path(__file__).resolve().parents[2]
PENDING = REPO / "tests" / "golden" / "shape" / "kfgqpc-rule6-pending.json"
ROUNDTRIP = REPO / "build" / "roundtrip"
OUT = REPO / "build" / "review" / "phase5" / "kfgqpc-rule6.html"
ENTRY = re.compile(r"^(\w+) (\S+): UnattachedMark \{ glyph: (\d+), cluster: (\d+) \}$")
CSS = """
body { font-family: system-ui, sans-serif; margin: 2rem; max-width: 80rem; }
table { border-collapse: collapse; margin: .5rem 0 2rem; }
td, th { border: 1px solid #ccc; padding: .3rem .8rem; }
.w { font-size: 4.5rem; direction: rtl; line-height: 1.6; }
"""


def main() -> int:
    pending = json.loads(PENDING.read_text(encoding="utf-8"))
    texts: dict[str, dict[str, str]] = {}
    by_glyph: dict[tuple[str, int], list[tuple[str, str]]] = defaultdict(list)
    names: dict[str, list[str]] = {}
    for entry in pending:
        m = ENTRY.match(entry)
        if not m:
            raise ValueError(f"unexpected entry {entry!r}")
        riwayah, item, glyph = m.group(1), m.group(2), int(m.group(3))
        if riwayah not in texts:
            path = ROUNDTRIP / f"{riwayah}.jsonl"
            recs = [json.loads(line) for line in path.read_text(encoding="ascii").splitlines()]
            texts[riwayah] = {r["id"]: spine.from_cps(r["text"]).strip() for r in recs}
            names[riwayah] = kfgqpc.font(riwayah).getGlyphOrder()
        by_glyph[(riwayah, glyph)].append((item, texts[riwayah][item]))
    faces = "".join(
        f"@font-face {{ font-family: k_{r}; src: url(data:font/ttf;base64,"
        f"{base64.b64encode(kfgqpc.font_bytes(r)).decode('ascii')}); }}\n"
        for r in texts
    )
    w = [
        "<!doctype html>\n<meta charset='utf-8'>\n<title>G-100 unanchored marks</title>\n",
        f"<style>{faces}{CSS}</style>\n<h1>G-100: marks the KFGQPC Warsh and Qalun fonts leave "
        "unanchored</h1>\n<p>Every word below, drawn in its riwayah's own KFGQPC font, has one "
        "mark glyph that the font places without an anchor (rule 6). Decide per glyph whether "
        "the mark sits where the print puts it. Generated by <code>python -m "
        "pipeline.review_phase5</code>.</p>\n",
    ]
    for (riwayah, glyph), words in sorted(by_glyph.items()):
        name = names[riwayah][glyph]
        w.append(f"<h2>{riwayah}: glyph {glyph} <code>{html.escape(name)}</code>, "
                 f"{len(words)} places</h2>\n<table>\n")  # fmt: skip
        for item, text in words:
            w.append(
                f"<tr><td>{item}</td><td class='w' style='font-family:k_{riwayah}'>"
                f"{html.escape(text)}</td></tr>\n"
            )
        w.append("</table>\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(w), encoding="utf-8")
    print(f"review_phase5: {len(pending)} places -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
