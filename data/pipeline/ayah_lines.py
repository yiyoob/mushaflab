"""T5.2: per-ayah page and line constraints of each riwayah's own KFGQPC layout (D1).

    python -m pipeline.ayah_lines write   # data/layout_inputs/<riwayah>.ayah-lines.yaml
    python -m pipeline.ayah_lines check   # exit 1 if a tracked file is stale

KFGQPC gives every ayah, in the riwayah's own numbering, the page it is on ("a-b" when it
crosses from page a to page b) and its first and last line. These are copied as they are, so
the core's line fitting (`core/mushaf-fitlines`) reads tracked text, not the pinned zips.
"""

import sys
from pathlib import Path

from pipeline import emit_patches, ingest_riwayah, kfgqpc
from pipeline.emit_patches import flow

OUT_DIR = Path(__file__).resolve().parents[1] / "layout_inputs"


def path_for(riwayah: str) -> Path:
    return OUT_DIR / f"{riwayah}.ayah-lines.yaml"


def entries(riwayah: str) -> list[dict]:
    out = []
    for r in kfgqpc.rows(riwayah):
        first, last = ingest_riwayah.parse_page(r["page"])
        out.append(
            {
                "surah": int(r["sura_no"]),
                "ayah": int(r["aya_no"]),
                "page": first,
                "last_page": last,
                "line_start": int(r["line_start"]),
                "line_end": int(r["line_end"]),
            }
        )
    return out


def render(riwayah: str) -> str:
    lines = [
        f"# Per-ayah page and lines of {riwayah}'s own KFGQPC layout, from "
        f"{kfgqpc.source_id(riwayah)}.",
        "# Generated by `python -m pipeline.ayah_lines write` (T5.2, D1). Do not edit.",
        f"riwayah: {flow(riwayah)}",
        f"source: {flow(kfgqpc.source_id(riwayah))}",
        f"spine: {flow(emit_patches.SPINE_ID)}",
        "ayahs:",
    ]
    lines += ["  - " + flow(e) for e in entries(riwayah)]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    cmd = argv[1] if len(argv) > 1 else "write"
    stale = []
    for r in kfgqpc.RIWAYAT:
        text, path = render(r), path_for(r)
        if cmd == "write":
            OUT_DIR.mkdir(exist_ok=True)
            path.write_text(text, encoding="ascii")
        elif not path.exists() or path.read_text(encoding="ascii") != text:
            stale.append(path.name)
    for name in stale:
        print(f"ayah_lines: {name} differs from a rebuild", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
