"""T4.5: write the raw patch files data/patches/raw/<riwayah>.yaml (D12 format, D20, D21).

    python -m pipeline.emit_patches write [RIWAYAH...]   # (re)write; default all 7
    python -m pipeline.emit_patches check                # exit 1 if a tracked file is stale

One flow-style patch per line, every string quoted, ASCII only, in reading order. Every
patch is `raw-derived`, `single_source: true` (D13) and carries a `difference_kind` (D21).
The output depends only on the pinned sources, the spine and the codepoint table.
"""

import functools
import hashlib
import json
import sys
from pathlib import Path

from pipeline import align, classify, differ, ingest_riwayah, kfgqpc, sources, spine
from pipeline.clusterize import clusterize
from pipeline.codepoints import load_table

RAW_DIR = Path(__file__).resolve().parents[1] / "patches" / "raw"
SPINE_ID = f"hafs/v{spine.SPINE_VERSION}"
ORDER = ("shuba", "qalun", "warsh", "bazzi", "qunbul", "susi", "duri_abuamr")


def path_for(riwayah: str) -> Path:
    return RAW_DIR / f"{riwayah}.yaml"


def source_ref(riwayah: str) -> str:
    sid = kfgqpc.source_id(riwayah)
    digest = hashlib.sha256(sources.path(sid).read_bytes()).hexdigest()
    return f"{sid}@{digest[:12]}"


@functools.cache
def _hafs() -> tuple[list[ingest_riwayah.Item], dict[str, dict]]:
    return ingest_riwayah.load("hafs").items, {r["id"]: r for r in spine.load_records()}


def changes_for(riwayah: str) -> list[differ.Change]:
    table = load_table()
    hafs_items, recs = _hafs()
    pairs = align.align_text(hafs_items, ingest_riwayah.load(riwayah).items)
    return differ.diff(pairs, recs, lambda t: clusterize(t, table))


def patch_dict(riwayah: str, change: differ.Change, ref: str, tag: classify.Tag) -> dict:
    d: dict = {
        "id": differ.patch_id(riwayah, change.key, change.op),
        "owner": {"level": "riwayah", "id": riwayah},
        "op": change.op,
        "target": change.target,
    }
    if change.payload:
        d["payload"] = change.payload
    d |= {
        "source": {"kind": "kfgqpc-diff", "ref": ref},
        "status": "raw-derived",
        "single_source": True,
        "difference_kind": tag.kind,
    }
    return d


def flow(value: object) -> str:
    """YAML flow style: strings double-quoted (ASCII, JSON escapes), ints and bools bare."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=True)
    if isinstance(value, list):
        return "[" + ", ".join(flow(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"{k}: {flow(v)}" for k, v in value.items()) + "}"
    raise TypeError(f"cannot write {type(value).__name__} as YAML")


def render(riwayah: str) -> str:
    ref = source_ref(riwayah)
    confirmed = classify.load_confirmed()[riwayah]
    lines = [
        f"# Raw patches for {riwayah} on the Hafs spine {SPINE_ID}, derived from {ref}.",
        "# Generated by `python -m pipeline.emit_patches write` (T4.5, D20). Do not edit.",
        f"spine: {flow(SPINE_ID)}",
        "patches:",
    ]
    for change in changes_for(riwayah):
        tag = classify.classify(change, confirmed)
        lines.append("  - " + flow(patch_dict(riwayah, change, ref, tag)))
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    command, names = (argv[1] if len(argv) > 1 else "check"), argv[2:]
    riwayat = names or list(ORDER)
    if command == "write":
        RAW_DIR.mkdir(parents=True, exist_ok=True)
        for r in riwayat:
            path_for(r).write_text(render(r), encoding="ascii")
            print(f"raw patches written: {path_for(r)}")
        return 0
    stale = [r for r in riwayat if not path_for(r).exists() or path_for(r).read_text() != render(r)]
    print("raw patches: " + (f"stale {stale}" if stale else "up to date"))
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
