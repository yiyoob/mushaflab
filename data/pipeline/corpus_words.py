"""M0.4: corpus/text/words.tsv from the Hafs spine (docs/formats.md, D69).

The spine (data/spine/hafs/v1) is the KFGQPC Hafs v2.0 text split into items and clusters by the
legacy pipeline (T1.2); its manifest pins the source file. This importer writes one row per spine
item, with the item's codepoints joined back into one text cell, so the word table holds exactly
the KFGQPC text (rule 1: nothing typed, only copied). Clusters are not stored: they are derived
again from the text with the codepoint table, and the test checks they equal the spine's.

    python -m pipeline.corpus_words write   # regenerate the table
    python -m pipeline.corpus_words check   # exit 1 if the tracked table is not current
"""

import json
import sys
from pathlib import Path

from pipeline import spine

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "corpus" / "text" / "words.tsv"
HEADER = ["word_id", "kind", "text", "sep_before", "sep_after", "source"]


def spine_items() -> list[dict]:
    with spine.ITEMS.open(encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def render() -> str:
    manifest = json.loads(spine.MANIFEST.read_text(encoding="utf-8"))
    src = manifest["source"]
    lines = [
        "# Every item of the KFGQPC Hafs text, in order (docs/formats.md).",
        f"# From data/spine/hafs/v1 (spine_version {manifest['spine_version']}), built from "
        f"{src['id']} member {src['member']} (sha256 {src['sha256']}).",
        "# Generated by `python -m pipeline.corpus_words write`. Do not edit.",
        "\t".join(HEADER),
    ]
    for it in spine_items():
        text = "".join(spine.from_cps(c["cps"]) for c in it["clusters"])
        row = [
            it["id"],
            it["kind"],
            text,
            it.get("sep_before", ""),
            it["sep_after"],
            f"kfgqpc-hafs:{it['id']}",
        ]
        if any("\t" in cell or "\n" in cell for cell in row):
            msg = f"{it['id']}: a cell holds a tab or newline"
            raise ValueError(msg)
        lines.append("\t".join(row))
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    cmd = argv[0] if argv else ""
    if cmd == "write":
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(render(), encoding="utf-8")
        print(f"corpus_words: wrote {OUT.relative_to(REPO)}")
        return 0
    if cmd == "check":
        current = OUT.is_file() and OUT.read_text(encoding="utf-8") == render()
        print("corpus_words: current" if current else "corpus_words: STALE, run write")
        return 0 if current else 1
    print("usage: python -m pipeline.corpus_words write|check", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
