"""Spike S4 (T0.6): what line layouts exist for the non-Hafs riwayat?

    uv run --directory data python -m spikes.s4_layouts > docs/spikes/s4-layouts.md

KFGQPC gives, per ayah, `page`, `line_start`, `line_end` for its own printed mushaf of
each riwayah. This checks those fields for consistency and measures what they can and
cannot determine. QUL (checked in T0.2) has no non-Hafs layouts.
"""

import sys
from collections import Counter, defaultdict

from spikes.common import kfgqpc_official, load_json, verified_sources

RIWAYAT = ["hafs", "shuba", "warsh", "qalun", "bazzi", "qunbul", "duri_abuamr", "susi"]
LINES_PER_PAGE = 15


def rows_for(rid: str) -> list[dict]:
    if rid == "bazzi":
        return load_json(verified_sources()["kfgqpc-mirror-bazzi-data"])  # type: ignore[return-value]
    return kfgqpc_official(rid)


def check(rid: str) -> dict:
    rows = rows_for(rid)
    pages = Counter()
    covered: dict[int, set[int]] = defaultdict(set)
    order_errors = bad_lines = 0
    multi_line = 0
    previous = (0, 0)
    cross_page = 0
    for r in rows:
        # An ayah running onto the next page has page "a-b": line_start is on a, line_end on b.
        first, _, last = str(r["page"]).partition("-")
        p0, p1 = int(first), int(last or first)
        start, end = int(r["line_start"]), int(r["line_end"])
        pages[p0] += 1
        pages[p1] += 0
        if p1 not in (p0, p0 + 1):
            bad_lines += 1
        if not (1 <= start <= LINES_PER_PAGE and 1 <= end <= LINES_PER_PAGE):
            bad_lines += 1
        if p0 == p1 and end < start:
            bad_lines += 1
        if (p0, start) < previous:
            order_errors += 1
        previous = (p1, end)
        if p0 == p1:
            multi_line += end > start
            covered[p0].update(range(start, end + 1))
        else:
            cross_page += 1
            multi_line += 1
            covered[p0].update(range(start, LINES_PER_PAGE + 1))
            covered[p1].update(range(1, end + 1))
    n_pages = max(pages)
    missing_pages = [p for p in range(1, n_pages + 1) if p not in pages]
    uncovered = Counter()
    for p in range(1, n_pages + 1):
        for line in range(1, LINES_PER_PAGE + 1):
            if line not in covered.get(p, set()):
                uncovered[p] += 1
    surahs = len({int(r["sura_no"]) for r in rows})
    return {
        "ayahs": len(rows),
        "pages": n_pages,
        "missing_pages": missing_pages,
        "bad_lines": bad_lines,
        "order_errors": order_errors,
        "multi_line": multi_line,
        "cross_page": cross_page,
        "uncovered_lines": sum(uncovered.values()),
        "surahs": surahs,
        "pages_with_uncovered": len(uncovered),
    }


def main() -> int:
    print("# Spike S4: line layouts for non-Hafs riwayat")
    print()
    print("Generated by `data/spikes/s4_layouts.py` from pinned KFGQPC data.")
    print()
    print(
        "| Riwayah | Ayahs | Pages | Missing pages | Line out of 1-15 | Order errors "
        "| Ayahs spanning >1 line | Crossing a page | Lines with no ayah | Surahs |"
    )
    print("|---|---|---|---|---|---|---|---|---|---|")
    results = {rid: check(rid) for rid in RIWAYAT}
    for rid, r in results.items():
        print(
            f"| {rid} | {r['ayahs']} | {r['pages']} | {len(r['missing_pages'])} "
            f"| {r['bad_lines']} | {r['order_errors']} | {r['multi_line']} | {r['cross_page']} "
            f"| {r['uncovered_lines']} | {r['surahs']} |"
        )
    print()
    print(
        "Lines with no ayah are surah-name and basmalah lines (and any gap). Hafs's count can "
        "be compared with the QUL 1441H layout's 114 surah-name + 112 basmalah lines on "
        "pages 3-604 plus the short pages 1-2."
    )
    print()

    def first_page(r: dict) -> int:
        return int(str(r["page"]).partition("-")[0])

    hafs = {(int(r["sura_no"]), int(r["aya_no"])): first_page(r) for r in rows_for("hafs")}
    print("Same page as Hafs for the same (surah, ayah) number:")
    print()
    for rid in RIWAYAT[1:]:
        rows = rows_for(rid)
        same = sum(
            1 for r in rows if hafs.get((int(r["sura_no"]), int(r["aya_no"]))) == first_page(r)
        )
        print(f"- {rid}: {same}/{len(rows)}")
    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
