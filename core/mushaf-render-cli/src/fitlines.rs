//! `mushaf-fitlines [riwayah...]` (T5.2, D29; host only, run from the repository root by
//! `just data-build`): fits each riwāyah's native layout with `mushaf_layout::native` and writes
//!
//! - `data/layouts/uthmani-<r>-kfgqpc.json` (the layout, a line's `fit` tag included),
//! - `data/render/uthmani-<r>-kfgqpc.line-widths.json` (its short lines, P5),
//! - `docs/review/phase5/layout-<r>.md` (the report: every line not fixed by the data).
//!
//! All logic is in `core/` crates (rule 7); this file reads inputs and writes outputs.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;
use std::process::ExitCode;

use mushaf_justify::ONE;
use mushaf_layout::fit::{LineWidths, Profile};
use mushaf_layout::native::{
    AyahLinesFile, NativeInput, NativeLayout, ShortLines, ayah_ranges, fit_native, lines_per_page,
    short_lines,
};
use mushaf_model::{Error, FitTag, Layout};
use mushaf_render::profile_path;
use mushaf_resolve::{Mode, Selection, resolve_profile};
use mushaf_shape::FontData;

const RIWAYAT: [&str; 7] = [
    "shuba",
    "warsh",
    "qalun",
    "bazzi",
    "qunbul",
    "duri_abuamr",
    "susi",
];

fn read(repo: &Path, rel: &str) -> Result<String, Error> {
    fs::read_to_string(repo.join(rel)).map_err(|e| Error::new(format!("{rel}: {e}")))
}

fn write(repo: &Path, rel: &str, text: &str) -> Result<(), Error> {
    let path = repo.join(rel);
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir).map_err(|e| Error::new(format!("{rel}: {e}")))?;
    }
    fs::write(&path, text).map_err(|e| Error::new(format!("{rel}: {e}")))
}

/// The layout as tracked JSON: metadata, then one line per row.
fn layout_json(layout: &Layout) -> Result<String, Error> {
    let mut head = layout.clone();
    head.lines.clear();
    let meta = serde_json::to_value(&head).map_err(|e| Error::new(e.to_string()))?;
    let mut s = String::from("{\n");
    for (k, v) in meta.as_object().expect("an object") {
        if k == "lines" {
            continue;
        }
        let _ = writeln!(s, "  {}: {},", serde_json::to_string(k).unwrap(), v);
    }
    s.push_str("  \"lines\": [\n");
    let rows: Vec<String> = layout
        .lines
        .iter()
        .map(|l| serde_json::to_string(l).map(|t| format!("    {t}")))
        .collect::<Result<_, _>>()
        .map_err(|e| Error::new(e.to_string()))?;
    s.push_str(&rows.join(",\n"));
    s.push_str("\n  ]\n}\n");
    Ok(s)
}

fn units(v: i64) -> String {
    format!("{}", v / ONE)
}

fn report_md(
    riwayah: &str,
    profile: &Profile,
    fitted: &NativeLayout,
    short: &ShortLines,
    unmeasured: usize,
) -> String {
    let mut s = String::new();
    let count = |t: FitTag| fitted.report.iter().filter(|r| r.fit == t).count();
    let _ = writeln!(s, "# Native layout: {riwayah} (T5.2, D29)\n");
    let _ = writeln!(
        s,
        "Generated by `mushaf-fitlines` (`just data-build`) from `data/layout_inputs/{riwayah}.ayah-lines.yaml` \
         (KFGQPC's own page and lines per ayah) and the 1441H Hafs breaks. Layout: \
         `data/layouts/{}.json`; font `{}`.\n",
        profile.layout_id, profile.font
    );
    let _ = writeln!(
        s,
        "Every text line is tagged: `forced` (the ayah lines fix the break), `hafs` (the Hafs \
         break at the same page and line, consistent with the ayah lines: a **hypothesis** for \
         this riwayah's print until spot-checked), `fitted` (chosen by width; on Hafs, where the \
         answer is known, width alone finds about 54% of such breaks).\n"
    );
    let _ = writeln!(s, "| Tag | Lines |\n|---|---|");
    for t in [FitTag::Forced, FitTag::Hafs, FitTag::Fitted] {
        let _ = writeln!(
            s,
            "| {} | {} |",
            serde_json::to_string(&t).unwrap().trim_matches('"'),
            count(t)
        );
    }
    let _ = writeln!(
        s,
        "\nTarget width for fitting: {} font units (median natural width of the lines whose \
         breaks the data fix on both sides). Items whose width could not be measured (no \
         encoding row yet, G-102): {unmeasured}.\n",
        units(fitted.target)
    );
    let mut full: Vec<i64> = fitted
        .report
        .iter()
        .filter(|r| !short.contains_key(&(r.page, r.line)))
        .filter_map(|r| r.natural)
        .collect();
    full.sort_unstable();
    if !full.is_empty() {
        let pct = |p: usize| units(full[(full.len() - 1) * p / 100]);
        let _ = writeln!(
            s,
            "Natural widths of full lines (font units): p1 {}, median {}, p90 {}, p99 {}. Profile \
             `line_width`: {}.\n",
            pct(1),
            pct(50),
            pct(90),
            pct(99),
            profile.geometry.line_width
        );
    }
    let fitted_lines: Vec<_> = fitted
        .report
        .iter()
        .filter(|r| r.fit == FitTag::Fitted)
        .collect();
    let _ = writeln!(s, "## Fitted lines ({})\n", fitted_lines.len());
    if fitted_lines.is_empty() {
        let _ = writeln!(s, "None.\n");
    } else {
        let _ = writeln!(
            s,
            "| Page:line | First | Last | Hafs line starts at | Allowed starts | Margin (font units) |\n|---|---|---|---|---|---|"
        );
        for r in fitted_lines {
            let (n, m) = r.alternatives.unwrap_or((0, None));
            let _ = writeln!(
                s,
                "| {}:{} | {} | {} | {} | {} | {} |",
                r.page,
                r.line,
                r.first,
                r.last,
                r.hafs_start.as_deref().unwrap_or("-"),
                n,
                m.map_or("-".into(), |v| (v / ONE).to_string())
            );
        }
        let _ = writeln!(s);
    }
    let pages_with_hafs: BTreeSet<u32> = fitted
        .report
        .iter()
        .filter(|r| r.fit == FitTag::Hafs)
        .map(|r| r.page)
        .collect();
    let _ = writeln!(
        s,
        "## Transferred Hafs breaks\n\n{} lines on {} pages take the Hafs break (listed in the \
         layout file as `\"fit\":\"hafs\"`).\n",
        count(FitTag::Hafs),
        pages_with_hafs.len()
    );
    let _ = writeln!(s, "## Short lines ({}, P5)\n", short.len());
    let _ = writeln!(
        s,
        "| Page:line | Width (ppm of a full line) | Basis |\n|---|---|---|"
    );
    for ((p, l), (ppm, basis)) in short {
        let _ = writeln!(
            s,
            "| {p}:{l} | {ppm} | {} |",
            serde_json::to_string(basis).unwrap().trim_matches('"')
        );
    }
    s
}

fn widths_json(layout_id: &str, short: &ShortLines) -> String {
    let mut s = format!(
        "{{\n \"layout_id\": \"{layout_id}\",\n \"rule\": \"P5 (D30): the Hafs print's width when the line holds the same items as the Hafs line at that page and line; its own natural share when that Hafs line is short but holds other items; else short when the natural width is under 600000 ppm of the median full line (calibrated on Hafs)\",\n \"basis\": [\n"
    );
    let basis: Vec<String> = short
        .iter()
        .map(|((p, l), (_, b))| {
            format!(
                "  {{\"page\": {p}, \"line\": {l}, \"basis\": {}}}",
                serde_json::to_string(b).unwrap()
            )
        })
        .collect();
    s.push_str(&basis.join(",\n"));
    s.push_str("\n ],\n \"short_lines\": [\n");
    let rows: Vec<String> = short
        .iter()
        .map(|((p, l), (ppm, _))| {
            format!("  {{\"page\": {p}, \"line\": {l}, \"width_ppm\": {ppm}}}")
        })
        .collect();
    s.push_str(&rows.join(",\n"));
    s.push_str("\n ]\n}\n");
    s
}

fn run_one(repo: &Path, ds: &mushaf_model::DataSet, riwayah: &str) -> Result<String, Error> {
    let profile = Profile::from_json(&read(repo, &profile_path(riwayah)?)?)?;
    let table = profile.encoding_table(|p| read(repo, p))?;
    let font = FontData::new(
        fs::read(repo.join(&profile.font))
            .map_err(|e| Error::new(format!("{}: {e}", profile.font)))?,
    )?;
    let shaper = font.shaper();
    let sel = Selection {
        riwayah: riwayah.into(),
        ..Selection::default()
    };
    let base = resolve_profile(ds, &sel, None, Mode::Data)
        .map_err(|e| Error::new(format!("resolve {riwayah}: {e}")))?;
    let mut widths = Vec::with_capacity(base.items.len());
    for it in &base.items {
        let cl: Vec<&[char]> = it.clusters.iter().map(|c| c.cps.0.as_slice()).collect();
        widths.push(match table.convert_item(&it.id.to_string(), &cl) {
            Ok(c) => Some(i64::from(shaper.width(&c.chars, &[])?) * ONE),
            Err(_) => None,
        });
    }
    let unmeasured = widths.iter().filter(|w| w.is_none()).count();
    let file: AyahLinesFile = mushaf_model::from_yaml(&read(
        repo,
        &format!("data/layout_inputs/{riwayah}.ayah-lines.yaml"),
    )?)?;
    let rp = &ds.profiles[riwayah];
    let map = rp.ayah_map.as_ref().map(|m| &ds.ayah_maps[m]);
    let hafs = &ds.layouts["uthmani-1441h"];
    let input = NativeInput {
        riwayah,
        layout_id: &profile.layout_id,
        text_source: &file.source,
        base: &base,
        ayahs: ayah_ranges(&base, map, &file)?,
        hafs,
        spine: &ds.spines[&profile.spine],
        lines_per_page: lines_per_page(hafs),
        headers: &rp.surah_headers,
        widths,
        space: mushaf_justify::space_width(&shaper)?,
    };
    let mut fitted = fit_native(&input)?;
    let hafs_widths =
        LineWidths::from_json(&read(repo, "data/render/uthmani-1441h.line-widths.json")?)?;
    let short = short_lines(&input, &fitted, &hafs_widths.short)?;
    for l in &mut fitted.layout.lines {
        if l.fit.is_some() {
            l.centered = short.contains_key(&(l.page, l.line));
        }
    }
    write(
        repo,
        &format!("data/layouts/{}.json", profile.layout_id),
        &layout_json(&fitted.layout)?,
    )?;
    write(
        repo,
        &profile.line_widths,
        &widths_json(&profile.layout_id, &short),
    )?;
    write(
        repo,
        &format!("docs/review/phase5/layout-{riwayah}.md"),
        &report_md(riwayah, &profile, &fitted, &short, unmeasured),
    )?;
    let count = |t: FitTag| fitted.report.iter().filter(|r| r.fit == t).count();
    Ok(format!(
        "{riwayah}: {} text lines (forced {}, hafs {}, fitted {}), {} short, {unmeasured} unmeasured items",
        fitted.report.len(),
        count(FitTag::Forced),
        count(FitTag::Hafs),
        count(FitTag::Fitted),
        short.len()
    ))
}

fn run() -> Result<(), Error> {
    let repo = std::env::current_dir().map_err(|e| Error::new(e.to_string()))?;
    let args: Vec<String> = std::env::args().skip(1).collect();
    let riwayat: Vec<&str> = if args.is_empty() {
        RIWAYAT.to_vec()
    } else {
        args.iter().map(String::as_str).collect()
    };
    let ds = mushaf_db::load_dir(&repo.join("data"))?;
    for r in riwayat {
        println!("{}", run_one(&repo, &ds, r)?);
    }
    Ok(())
}

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("mushaf-fitlines: {e}");
            ExitCode::FAILURE
        }
    }
}
