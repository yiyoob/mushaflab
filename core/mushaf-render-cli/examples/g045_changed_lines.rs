//! G-045 / D17: every line whose fitted output differs between the pinned DigitalKhatt font
//! and the derived render font (same profile otherwise). Writes docs/review/g045-changed-lines.md.
//!
//!     cargo run --release -p mushaf-render-cli --example g045_changed_lines
use std::collections::BTreeMap;
use std::fmt::Write;

use mushaf_render::Renderer;

fn main() {
    let repo = std::env::current_dir().unwrap();
    let new = Renderer::load(&repo, "hafs").unwrap();
    let mut old = Renderer::load(&repo, "hafs").unwrap();
    let pinned = std::fs::read(repo.join("fonts/digitalkhatt/hb-madina.otf")).unwrap();
    old.font = mushaf_shape::FontData::new(pinned).unwrap();
    let res = new.resolve(None).unwrap();
    let map = new.map(&res).unwrap();
    let mut pages: BTreeMap<u32, Vec<String>> = BTreeMap::new();
    let (mut lines, mut reshaped_lines, mut words, mut scaled) = (0, 0, 0, 0);
    for page in 1..=604 {
        let (a, b) = (
            old.fit(&res, &map, page).unwrap(),
            new.fit(&res, &map, page).unwrap(),
        );
        scaled += usize::from(a.scale != b.scale);
        for (la, lb) in a.lines.iter().zip(&b.lines) {
            if serde_json::to_string(la).unwrap() == serde_json::to_string(lb).unwrap() {
                continue;
            }
            let n = la
                .words
                .iter()
                .zip(&lb.words)
                .filter(|(x, y)| x.glyphs != y.glyphs)
                .count();
            lines += 1;
            words += n;
            reshaped_lines += usize::from(n > 0);
            pages.entry(page).or_default().push(if n > 0 {
                format!("{}", la.line)
            } else {
                format!("{}*", la.line)
            });
        }
    }
    let mut md = String::new();
    writeln!(md, "# G-045: lines changed by the D17 render font\n").unwrap();
    writeln!(md, "Generated by `cargo run --release -p mushaf-render-cli --example g045_changed_lines`: every \
        line whose fit (glyphs, widths, spaces, squeeze) differs between the pinned DigitalKhatt Madina \
        font and the derived render font, all else equal. A line number marked `*` only re-fits because \
        its page's font scale changed; the others contain a word whose superscript alef (U+0670) the \
        pinned font drew as a spacing upright alef.\n").unwrap();
    writeln!(md, "- Changed lines: {lines} on {} pages ({reshaped_lines} with reshaped words, {words} words; {} re-fit only).", pages.len(), lines - reshaped_lines).unwrap();
    writeln!(md, "- Pages whose font scale changed: {scaled}.\n").unwrap();
    writeln!(md, "| Page | Lines |\n|---|---|").unwrap();
    for (p, ls) in &pages {
        writeln!(md, "| {p} | {} |", ls.join(", ")).unwrap();
    }
    std::fs::write(repo.join("docs/review/g045-changed-lines.md"), md).unwrap();
    println!("changed lines {lines} on {} pages", pages.len());
}
